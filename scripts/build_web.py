"""Build the browser app: WebAssembly engine, JS bindings, then the Vite bundle.

Requires Rust with the wasm32-unknown-unknown target, `wasm-bindgen-cli` matching
the locked wasm-bindgen version, Node.js and the npm packages in `web/`.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def run(command, cwd=ROOT):
    print('+', ' '.join(map(str, command)), flush=True)
    subprocess.run(command, cwd=cwd, check=True, shell=sys.platform == 'win32' and command[0] in ('npm', 'npx'))


def notices():
    """The app ships the Rust notices for its engine plus each npm runtime package's licence."""
    web = ROOT/'web'
    lock = json.loads((web/'package-lock.json').read_text(encoding='utf-8'))
    parts = [(ROOT/'THIRD_PARTY_NOTICES').read_text(encoding='utf-8').rstrip('\n'), '',
             '# Browser app JavaScript runtime packages', '',
             'Generated by `python scripts/build_web.py` from web/package-lock.json. Build tools',
             '(Vite, TypeScript, Playwright) are not shipped.', '']
    for key, package in sorted(lock['packages'].items()):
        if not key.startswith('node_modules/') or package.get('dev') or key.count('node_modules/') != 1:
            continue
        name = key.removeprefix('node_modules/')
        licences = sorted((web/key).glob('LICEN[CS]E*'))
        if not licences:
            sys.exit(f'{name} ships no licence file')
        parts += [f'## {name} {package["version"]} ({package.get("license", "unknown")})', '',
                  licences[0].read_text(encoding='utf-8').strip(), '']
    (web/'public').mkdir(exist_ok=True)
    (web/'public/THIRD_PARTY_NOTICES.txt').write_text('\n'.join(parts), encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--skip-bundle', action='store_true', help='only rebuild the WebAssembly package')
    parser.add_argument('--test', action='store_true', help='then run the Playwright tests in Chromium and Firefox')
    args = parser.parse_args()
    lock = (ROOT/'Cargo.lock').read_text(encoding='utf-8')
    version = re.search(r'name = "wasm-bindgen"\nversion = "([^"]+)"', lock).group(1)
    installed = subprocess.run(['wasm-bindgen', '--version'], capture_output=True, text=True).stdout.split()[-1]
    if installed != version:
        sys.exit(f'wasm-bindgen {installed} does not match the locked {version}: '
                 f'cargo install wasm-bindgen-cli --version {version} --locked')
    run(['cargo', 'build', '--locked', '--release', '-p', 'nestbolt-wasm', '--target', 'wasm32-unknown-unknown'])
    out = ROOT/'web/src/pkg'
    shutil.rmtree(out, ignore_errors=True)
    run(['wasm-bindgen', '--target', 'web', '--out-dir', str(out),
         str(ROOT/'target/wasm32-unknown-unknown/release/nestbolt_wasm.wasm')])
    if not args.skip_bundle:
        notices()
        run(['npm', 'run', 'build'], cwd=ROOT/'web')
    if args.test:
        run(['npx', 'tsc', '-p', 'tsconfig.tests.json'], cwd=ROOT/'web')
        run(['npx', 'playwright', 'test'], cwd=ROOT/'web')


if __name__ == '__main__':
    main()
