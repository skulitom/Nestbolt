"""Generate the bundled example: a finger-jointed box, 99 x 63 x 45 mm outside,
for 3 mm sheet. Six panels; every mating edge pairs a tab (A edge) with a slot
(B edge): front/back have A edges all round, top/bottom B edges all round, and
the sides B edges where they meet front/back and A edges where they meet
top/bottom. Panels are built on a 1 mm grid and traced as exact rectilinear
outlines. Writes examples/box-99x63x45.svg and web/public/example-box.svg.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
T = 3            # material thickness, mm
W, D, H = 99, 63, 45
SEGMENTS = {W: 9, D: 7, H: 5}  # odd counts; every finger is a whole number of mm


def panel(width, height, horizontal, vertical):
    """Material cells of a width x height panel; `horizontal`/`vertical` are the
    edge types ('A': segments 0, 2, ... are tabs; 'B': they are slots)."""
    cells = [[True] * width for _ in range(height)]

    def notch(x0, y0, x1, y1):
        for y in range(y0, y1):
            for x in range(x0, x1):
                cells[y][x] = False

    for kind, length, along in [(horizontal, width, 'x'), (vertical, height, 'y')]:
        n = SEGMENTS[length]
        step = length // n
        for k in range(n):
            slot = (k % 2 == 1) if kind == 'A' else (k % 2 == 0)
            if not slot:
                continue
            a, b = k * step, (k + 1) * step
            if along == 'x':
                notch(a, 0, b, T)
                notch(a, height - T, b, height)
            else:
                notch(0, a, T, b)
                notch(width - T, a, width, b)
    return cells


def outline(cells):
    """The boundary of the material cells as one counter-clockwise loop (y up)."""
    height, width = len(cells), len(cells[0])
    solid = lambda x, y: 0 <= x < width and 0 <= y < height and cells[y][x]
    edges = {}
    for y in range(height):
        for x in range(width):
            if not cells[y][x]:
                continue
            # Directed unit edges with the material on their left.
            if not solid(x, y - 1):
                edges[(x, y)] = (x + 1, y)
            if not solid(x + 1, y):
                edges[(x + 1, y)] = (x + 1, y + 1)
            if not solid(x, y + 1):
                edges[(x + 1, y + 1)] = (x, y + 1)
            if not solid(x - 1, y):
                edges[(x, y + 1)] = (x, y)
    start = min(edges)
    loop, point = [start], edges[start]
    while point != start:
        loop.append(point)
        point = edges[point]
    # Keep only corners.
    corners = [p for i, p in enumerate(loop)
               if (loop[i - 1][0] - p[0]) * (loop[(i + 1) % len(loop)][1] - p[1])
               != (loop[i - 1][1] - p[1]) * (loop[(i + 1) % len(loop)][0] - p[0])]
    assert len(edges) == len(loop), 'panel must be one connected outline'
    return corners


def main():
    panels = [('front', W, H, 'A', 'A'), ('back', W, H, 'A', 'A'),
              ('left', D, H, 'A', 'B'), ('right', D, H, 'A', 'B'),
              ('top', W, D, 'B', 'B'), ('bottom', W, D, 'B', 'B')]
    gap, x, paths = 8, 0, []
    for name, w, h, horizontal, vertical in panels:
        pts = outline(panel(w, h, horizontal, vertical))
        # SVG y runs down: flip each panel within its own box.
        d = 'M ' + ' L '.join(f'{x + px} {h - py}' for px, py in pts) + ' Z'
        paths.append(f'  <path id="{name}" d="{d}"/>')
        x += w + gap
    width, height = x - gap, max(h for _, _, h, _, _ in panels)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}mm" height="{height}mm" '
           f'viewBox="0 0 {width} {height}" fill="none" stroke="black" stroke-width="0.2">\n'
           f'  <!-- Finger-jointed box, {W} x {D} x {H} mm outside, 3 mm sheet. Generated by '
           f'scripts/make_example_box.py; MIT. -->\n' + '\n'.join(paths) + '\n</svg>\n')
    for target in [ROOT/'examples/box-99x63x45.svg', ROOT/'web/public/example-box.svg']:
        target.write_text(svg, encoding='utf-8', newline='\n')
        print(target)


if __name__ == '__main__':
    main()
