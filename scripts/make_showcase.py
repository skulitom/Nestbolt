"""Generate the README showcase drawing: glyph outlines in several sizes, many
with holes, so a nest shows curves, rotations and part-in-part placement.

Glyphs are DejaVu Sans Bold outlines from matplotlib's bundled font (Bitstream
Vera / DejaVu licence; the outlines are used as drawing geometry, the font
itself is not redistributed). Quadratic and cubic Béziers are kept exactly.
Writes examples/showcase-letters.svg; with --nest SECONDS it also imports the
drawing with the release CLI, nests it (request built by source element name)
and renders docs/images/showcase.png from the exported layout.
"""
import argparse
import json
import math
from pathlib import Path
import shutil
import subprocess

from matplotlib.font_manager import FontProperties
from matplotlib.path import Path as MPath
from matplotlib.textpath import TextPath

ROOT = Path(__file__).resolve().parents[1]
FONT = FontProperties(family='DejaVu Sans', weight='bold')
# (characters, cap height in mm, copies of each)
SETS = [
    ('NESTBOLT', 150, 1),
    ('aegopqdb@&80', 52, 4),
    ('aeoBDPRQ%96', 26, 11),
    ('aeosgbdpq80@', 12, 21),
]
SHEET = (850, 425)


def glyph(char, size):
    """SVG path data for one glyph scaled to `size` mm cap height, origin at 0."""
    path = TextPath((0, 0), char, size=size / 0.73, prop=FONT)
    verts, codes = path.vertices, path.codes
    xmin, ymin = verts[:, 0].min(), verts[:, 1].min()
    pt = lambda v: f'{v[0] - xmin:.4f} {-(v[1] - ymin):.4f}'
    out, i = [], 0
    while i < len(codes):
        code = codes[i]
        if code == MPath.MOVETO:
            out.append('M ' + pt(verts[i]))
            i += 1
        elif code == MPath.LINETO:
            out.append('L ' + pt(verts[i]))
            i += 1
        elif code == MPath.CURVE3:
            out.append(f'Q {pt(verts[i])} {pt(verts[i + 1])}')
            i += 2
        elif code == MPath.CURVE4:
            out.append(f'C {pt(verts[i])} {pt(verts[i + 1])} {pt(verts[i + 2])}')
            i += 3
        elif code == MPath.CLOSEPOLY:
            out.append('Z')
            i += 1
        else:
            i += 1
    return ' '.join(out), verts[:, 0].max() - xmin, verts[:, 1].max() - ymin


def draw():
    elements, copies, x, y, row = [], {}, 0.0, 0.0, 0.0
    for chars, size, count in SETS:
        for char in chars:
            d, w, h = glyph(char, size)
            name = f'{"upper" if char.isupper() else "glyph"}-{ord(char):x}-{size}'
            # Lay the source drawing out in rows; nesting ignores these positions.
            if x + w > 1200:
                x, y, row = 0.0, y + row + 10, 0.0
            elements.append(f'  <path id="{name}" transform="translate({x:.3f} {y + h:.3f})" d="{d}"/>')
            copies[name] = count
            x += w + 10
            row = max(row, h)
    height = y + row
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="1200mm" height="{height:.1f}mm" '
           f'viewBox="0 0 1200 {height:.1f}" fill="none" stroke="black" stroke-width="0.3">\n'
           '  <!-- README showcase: DejaVu Sans Bold glyph outlines (Bitstream Vera / DejaVu licence)\n'
           '       in four sizes. Generated by scripts/make_showcase.py. -->\n'
           + '\n'.join(elements) + '\n</svg>\n')
    drawing = ROOT/'examples/showcase-letters.svg'
    drawing.write_text(svg, encoding='utf-8', newline='\n')
    print(drawing, len(copies), 'glyphs')
    return drawing, copies


def nest(drawing, copies, seconds, seed):
    cli = ROOT/'target/release/nestbolt.exe'
    work = ROOT/'output/showcase'
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    subprocess.run([str(cli), 'import', str(drawing), '--output', str(work/'library.json')],
                   check=True, capture_output=True)
    library = json.loads((work/'library.json').read_text(encoding='utf-8'))
    # A glyph may import as several parts (the rings of %); each keeps its copies.
    request = {
        'name': 'README showcase',
        'parts': [{'id': p['id'], 'quantity': copies[p['source'].split('#')[1]],
                   'rotations': {'kind': 'step', 'degrees': 90}} for p in library['parts']],
        'sheets': [{'width_mm': SHEET[0], 'height_mm': SHEET[1],
                    'margins_mm': {'left': 5, 'right': 5, 'bottom': 5, 'top': 5}}],
        'spacing_mm': 1.0, 'edge_spacing_mm': 1.0,
    }
    (work/'request.json').write_text(json.dumps(request, indent=1), encoding='utf-8')
    done = subprocess.run([str(cli), 'nest', '--library', str(work/'library.json'),
                           '--request', str(work/'request.json'), '--out-dir', str(work/'run'),
                           '--seconds', str(seconds), '--seed', str(seed)], capture_output=True, text=True)
    if done.returncode:
        raise SystemExit(done.stderr)
    return work


def render(work):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.patches import PathPatch
    report = json.loads((work/'run/report.json').read_text(encoding='utf-8'))
    job = json.loads((work/'run/job.json').read_text(encoding='utf-8'))
    layout = json.loads((work/'run/layout.json').read_text(encoding='utf-8'))
    parts = {p['id']: p for p in job['parts']}
    sheets = [s['id'] for s in layout['sheets']]
    w, h = SHEET
    fig, axes = plt.subplots(len(sheets), 1, figsize=(12, 6 * len(sheets)), squeeze=False)
    for ax, sheet in zip(axes[:, 0], sheets):
        ax.add_patch(plt.Rectangle((0, 0), w, h, fill=False, lw=1.2, color='#444'))
        for pl in layout['placements']:
            if pl['sheet_id'] != sheet:
                continue
            t = pl['transform']
            c, s = math.cos(t['rotation_radians']), math.sin(t['rotation_radians'])
            for g in parts[pl['part_id']]['geometry']:
                verts, codes = [], []
                for ring in [g['outer'], *g['holes']]:
                    pts = [((-x if t['mirrored'] else x) * c - y * s + t['translation'][0],
                            (-x if t['mirrored'] else x) * s + y * c + t['translation'][1]) for x, y in ring]
                    verts += pts + [pts[0]]
                    codes += [MPath.MOVETO] + [MPath.LINETO] * (len(pts) - 1) + [MPath.CLOSEPOLY]
                ax.add_patch(PathPatch(MPath(verts, codes), facecolor='white', edgecolor='black', lw=0.45))
        ax.set_xlim(-2, w + 2)
        ax.set_ylim(-2, h + 2)
        ax.set_aspect('equal')
        ax.axis('off')
    plt.subplots_adjust(0, 0, 1, 1)
    out = ROOT/'docs/images/showcase.png'
    plt.savefig(out, dpi=110, facecolor='white')
    m = report['validation']['metrics']
    print(out, f"{m['placed_parts']} parts, {m['sheets_used']} sheet(s), {report['parts_in_holes']} in holes, "
          f"material {m['normalized_material']:.3f}, utilisation {m['utilization']:.1%}, "
          f"valid {report['validation']['valid']}")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--nest', type=float, metavar='SECONDS', help='also nest and render the README image')
    parser.add_argument('--seed', type=int, default=0)
    args = parser.parse_args()
    drawing, copies = draw()
    if args.nest:
        render(nest(drawing, copies, args.nest, args.seed))
