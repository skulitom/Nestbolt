"""Generate the locked Rust dependency inventory and retain available notices."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_NOTICES"


def render(historical=False, lbf=False, sparrow=False):
    command = ["cargo", "metadata", "--locked", "--format-version", "1"]
    if historical:
        command.extend(["--manifest-path", str(ROOT / "benchmarks/sparrow-repro/Cargo.toml")])
    if lbf:
        command.extend(["--manifest-path", str(ROOT / ".cache/upstream/jagua-rs/Cargo.toml")])
    if sparrow:
        command.extend(["--manifest-path", str(ROOT / "benchmarks/sparrow-benchmark/Cargo.toml")])
    metadata = json.loads(subprocess.check_output(
        command, cwd=ROOT, text=True, encoding="utf-8"
    ))
    packages = sorted(
        (p for p in metadata["packages"] if p["source"] is not None or lbf),
        key=lambda p: (p["name"], p["version"]),
    )
    lines = [
        "# Third-party notices", "",
        "Generated by `python scripts/notices.py` from Cargo.lock. Includes development",
        "and target-specific dependencies; this is an inventory, not a compatibility opinion.",
        "Dependencies remain under their own licences. Nestbolt's original code is MIT.", "",
        "jagua-rs 1.1.0 is used unmodified under MPL-2.0. Source:",
        "https://github.com/JeroenGar/jagua-rs (also available via crates.io).", "",
        "Credit: Jeroen Gardeyn and the jagua-rs / sparrow research projects.",
        "Current Sparrow is a separately downloaded MIT benchmark executable.",
        "The historical M0 Sparrow 0.1.0 and jagua-rs 0.6.2 are MPL-2.0 and unmodified.",
        "Their isolated adapter also uses MPL-2.0; see benchmarks/sparrow-repro/UPSTREAM_LICENSE",
        "and its separate THIRD_PARTY_NOTICES. They are not linked into the product.",
        "No sparrow/studio source is currently reused.", "",
        "| Package | Version | Declared SPDX licence | Source |",
        "| --- | --- | --- | --- |",
    ]
    if historical:
        lines[2:8] = [
            "Generated by `python scripts/notices.py --historical` from the isolated Cargo.lock.",
            "Includes development and target-specific dependencies, not just linked Windows code.",
            "This is the historical M0 benchmark adapter, not the product dependency inventory.",
            "Sparrow 0.1.0 and jagua-rs 0.6.2 are used unmodified under MPL-2.0.",
            "The adapter's orchestration is adapted from Sparrow's bench.rs under MPL-2.0.", "",
        ]
    elif lbf:
        lines = [
            "# LBF benchmark third-party notices", "",
            "Generated by `python scripts/notices.py --lbf` from the pinned upstream Cargo.lock.",
            "Includes development and target-specific dependencies, not just linked Windows code.",
            "This separately compiled benchmark executable is not linked into the product.",
            "jagua-rs 1.1.0 and its one-pass LBF implementation are used unmodified under MPL-2.0.",
            "Credit: Jeroen Gardeyn. Source revision:",
            "https://github.com/JeroenGar/jagua-rs/tree/9e00fd867be0fc493002aea68a1c6613d5b833d6", "",
            "The complete upstream MPL-2.0 licence is retained in UPSTREAM_LICENSE beside this file.", "",
            "| Package | Version | Declared SPDX licence | Source |",
            "| --- | --- | --- | --- |",
        ]
    elif sparrow:
        lines = [
            "# Current Sparrow comparator third-party notices", "",
            "Generated by `python scripts/notices.py --sparrow` from the isolated Cargo.lock.",
            "Includes development and target-specific dependencies, not just linked Windows code.",
            "The public-API benchmark wrapper is separate from the Nestbolt product.",
            "Sparrow 0.3.0 (MIT) and jagua-rs 1.1.0 (MPL-2.0) are unmodified dependencies.",
            "Credit: Jeroen Gardeyn. Sparrow source revision:",
            "https://github.com/JeroenGar/sparrow/tree/4629b22795ae6b25b3b460ccde6fb36a71292b6d", "",
            "The full upstream MIT licence is retained in UPSTREAM_LICENSE beside this file.", "",
            "| Package | Version | Declared SPDX licence | Source |",
            "| --- | --- | --- | --- |",
        ]
    else:
        lines = [line.replace('No sparrow/studio source is currently reused.',
                 'Nestbolt adapts the MIT Sparrow overlap-area penalty in crates/core/src/construct/repair/relax.rs; no Studio UI source is reused.')
                 for line in lines]
        lines[16:16] = [
            "Adapted source: Sparrow 0.3.0 src/quantify/{mod.rs,overlap_proxy.rs},",
            "https://github.com/JeroenGar/sparrow/tree/4629b22795ae6b25b3b460ccde6fb36a71292b6d",
            "Copyright (c) 2025 Jeroen Gardeyn, KU Leuven. Full MIT text: crates/core/Sparrow_LICENSE.", "",
            "Native strip parity also links the unmodified pinned Sparrow 0.3.0 library.",
            "This timed diagnostic is separate from the fixed-sheet browser engine.", "",
            "jagua-rs's unmodified LBF is a separately compiled MPL-2.0 benchmark executable.",
            "See benchmarks/lbf/UPSTREAM_LICENSE and its own THIRD_PARTY_NOTICES.", "",
            "Maker dataset sources and isolated authoring tools retain their own licences.",
            "See benchmarks/makers/README.md, sources.json and licenses/; none is linked into the app.", "",
        ]
    texts = {}
    if not (historical or lbf or sparrow):
        content = (ROOT/'crates/core/Sparrow_LICENSE').read_text(encoding='utf-8').strip()
        texts[content] = ['Sparrow 0.3.0 overlap penalty adaptation / crates/core/Sparrow_LICENSE']
    for package in packages:
        directory = Path(package["manifest_path"]).parent
        licence = package["license"]
        if (historical and package["name"] == "sparrow"
                and package["source"].endswith("#7f069e9d146f5599d7ba69a47ab4e8097c56e54f")):
            assert (directory / "LICENSE").read_text(encoding="utf-8").startswith("Mozilla Public License Version 2.0")
            licence = "MPL-2.0 (verified LICENSE; absent from historical manifest)"
        if (package['name'] == 'sparrow' and package.get('source')
                and package['source'].endswith('#4629b22795ae6b25b3b460ccde6fb36a71292b6d')):
            assert (directory / 'LICENSE').read_text(encoding='utf-8').startswith('MIT License')
            licence = 'MIT (verified LICENSE; absent from manifest)'
        if not licence:
            raise RuntimeError(f"Missing licence metadata: {package['name']}")
        source = package.get("repository") or f"https://crates.io/crates/{package['name']}"
        lines.append(f"| {package['name']} | {package['version']} | {licence} | {source} |")
        candidates = {
            p for p in directory.iterdir()
            if p.is_file() and p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"))
        }
        if package.get("license_file"):
            candidates.add(directory / package["license_file"])
        for path in sorted(candidates):
            content = "\n".join(line.rstrip() for line in path.read_text(encoding="utf-8").splitlines()).strip()
            texts.setdefault(content, []).append(f"{package['name']} {package['version']} / {path.name}")
    lines.extend(["", "# Supplied licence and notice texts", "", "Identical texts are printed once with every supplying package listed.", ""])
    for index, (content, sources) in enumerate(texts.items(), 1):
        lines.extend([f"## Notice {index}", ""])
        lines.extend(f"- {source}" for source in sources)
        lines.extend(["", "````text", content, "````", ""])
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    kinds = parser.add_mutually_exclusive_group()
    kinds.add_argument("--historical", action="store_true")
    kinds.add_argument("--lbf", action="store_true")
    kinds.add_argument("--sparrow", action="store_true")
    args = parser.parse_args()
    expected = render(args.historical, args.lbf, args.sparrow)
    output = ROOT / "benchmarks/sparrow-repro/THIRD_PARTY_NOTICES" if args.historical else (
        ROOT / "benchmarks/lbf/THIRD_PARTY_NOTICES" if args.lbf else (
        ROOT / "benchmarks/sparrow-benchmark/THIRD_PARTY_NOTICES" if args.sparrow else OUTPUT))
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != expected:
            raise SystemExit("THIRD_PARTY_NOTICES is stale. Run python scripts/notices.py")
        print("Dependency notices match Cargo.lock.")
    else:
        output.write_text(expected, encoding="utf-8", newline="\n")
        print("Updated THIRD_PARTY_NOTICES.")


if __name__ == "__main__":
    main()
