"""Write the browser app's example drawings and their manifest to web/public/examples.

Each example is one SVG whose outlines carry element ids, plus an entry in
examples.json with quantities by id, rotations, the sheet and a time budget.
Sources (licences in web/public/examples/LICENSES.txt):

- boxes: two finger-jointed boxes from scripts/make_example_box.py (MIT, ours);
- letters: DejaVu Sans Bold glyph outlines in four sizes, as in the README
  showcase (Bitstream Vera / DejaVu licence; outlines used as drawing geometry);
- mechanical: the procedural brackets, cogs, frames and inserts of the
  development job m-mechanical-frame-inserts (ours, MIT);
- sewing: FreeSewing 4.10.2 Teagan T-shirt pieces with 10 mm seam allowance,
  ten garments, from m-garment-teagan-2 (FreeSewing, MIT);
- gears: Steren's public-domain (CC0) gear from Openclipart in two sizes, from
  m-public-gear-1.
"""
import json
from pathlib import Path
import re
import shutil

from make_showcase import glyph

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'web/public/examples'
ASSETS = ROOT/'benchmarks/datasets/maker-assets'
LETTERS = [('NESTBOLT', 80, 1), ('aegopqdb@&80', 28, 2), ('aeoBDPRQ%96', 14, 4), ('aeosgbdpq80@', 7, 6)]
FOUR = {'kind': 'list', 'degrees': [0, 90, 180, 270]}


def letters():
    elements, quantities, x, y, row = [], {}, 0.0, 0.0, 0.0
    for chars, size, count in LETTERS:
        for char in chars:
            d, w, h = glyph(char, size)
            name = f'{"letter" if char.isalnum() else "sign"}-{char if char.isalnum() else ord(char)}-{size}mm'
            if x + w > 700:
                x, y, row = 0.0, y + row + 6, 0.0
            elements.append(f'  <path id="{name}" transform="translate({x:.3f} {y + h:.3f})" d="{d}"/>')
            quantities[name] = count
            x += w + 6
            row = max(row, h)
    height = y + row
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="700mm" height="{height:.1f}mm" '
           f'viewBox="0 0 700 {height:.1f}" fill="none" stroke="black" stroke-width="0.3">\n'
           '  <!-- Nestbolt example: DejaVu Sans Bold glyph outlines (Bitstream Vera / DejaVu licence)\n'
           '       in four sizes. Generated by scripts/make_web_examples.py. -->\n'
           + '\n'.join(elements) + '\n</svg>\n')
    (OUT/'letters.svg').write_text(svg, encoding='utf-8', newline='\n')
    return quantities


def from_asset(job, name, credit):
    """Copy a maker drawing, moving each group's id onto its outline so the app can name it."""
    text = (ASSETS/job/'parts.svg').read_text(encoding='utf-8')
    quantities = {gid: int(q) for q, gid in re.findall(r'<g data-quantity="(\d+)" id="([^"]+)"', text)}
    text = re.sub(r'<g data-quantity="\d+" id="([^"]+)"([^>]*)><path ', r'<g\2><path id="\1" ', text)
    head = text.index('>', text.index('<svg')) + 1
    text = text[:head] + f'<!-- Nestbolt example: {credit} -->' + text[head:]
    (OUT/f'{name}.svg').write_text(text, encoding='utf-8', newline='\n')
    return quantities


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT/'examples/box-99x63x45.svg', OUT/'boxes.svg')
    glyphs = letters()
    examples = [
        {'id': 'boxes', 'title': 'two finger-jointed boxes', 'file': 'boxes.svg',
         'summary': 'Ten panels of two 99 × 63 × 45 mm boxes on a 400 × 300 mm laser bed.',
         'quantities': {}, 'default_quantity': 2, 'rotations': FOUR,
         'sheet': [400, 300], 'margin': 5, 'spacing': 1, 'edge': 1, 'seconds': 10},
        {'id': 'letters', 'title': 'letters inside letters', 'file': 'letters.svg',
         'summary': f'{sum(glyphs.values())} glyphs in four sizes; small ones nest inside the holes of large ones.',
         'quantities': glyphs, 'rotations': FOUR,
         'sheet': [600, 400], 'margin': 5, 'spacing': 1, 'edge': 1, 'seconds': 30},
        {'id': 'mechanical', 'title': 'a mechanical kit', 'file': 'mechanical.svg',
         'summary': '138 brackets, cogs, frames and inserts on a 1220 × 2440 mm plywood sheet; inserts go in the frames.',
         'quantities': from_asset('m-mechanical-frame-inserts', 'mechanical', 'procedural brackets, cogs, frames and inserts (Nestbolt, MIT)'),
         'rotations': FOUR, 'overrides': {'cog': {'kind': 'free'}},
         'sheet': [1220, 2440], 'margin': 5, 'spacing': 1.5, 'edge': 1.5, 'seconds': 30},
        {'id': 'sewing', 'title': 'a sewing pattern', 'file': 'sewing.svg',
         'summary': 'Ten FreeSewing T-shirts (40 pieces) on a 1500 mm fabric roll; grain keeps pieces at 0° or 180°.',
         'quantities': from_asset('m-garment-teagan-2', 'sewing', 'FreeSewing 4.10.2 Teagan pieces with 10 mm seam allowance (FreeSewing, MIT)'),
         'rotations': {'kind': 'list', 'degrees': [0, 180]},
         'sheet': [1500, 4000], 'margin': 0, 'spacing': 3, 'edge': 1, 'seconds': 30},
        {'id': 'gears', 'title': 'interlocking gears', 'file': 'gears.svg',
         'summary': '40 gears in two sizes with free rotation, so teeth can mesh, on a 300 × 200 mm bed.',
         'quantities': from_asset('m-public-gear-1', 'gears', "Steren's gear from Openclipart (public domain, CC0)"),
         'rotations': {'kind': 'free'},
         'sheet': [300, 200], 'margin': 5, 'spacing': 1, 'edge': 1, 'seconds': 20},
    ]
    (OUT/'examples.json').write_text(json.dumps(examples, indent=1) + '\n', encoding='utf-8', newline='\n')
    licences = ROOT/'benchmarks/makers/licenses'
    notice = ['Licences for the drawings in this folder (see examples.json for which is which).', '',
              '## boxes.svg, mechanical.svg', '', 'Generated by Nestbolt scripts; MIT, see the main LICENSE.', '',
              '## letters.svg', '',
              'Glyph outlines of DejaVu Sans Bold, used as drawing geometry. DejaVu fonts are based on',
              'Bitstream Vera (Copyright (c) 2003 by Bitstream, Inc.); DejaVu changes are in the public domain.',
              'Bitstream Vera is a trademark of Bitstream, Inc. The font itself is not included.', '',
              "## gears.svg", '', "Steren's Gear from Openclipart, dedicated to the public domain (CC0).", '',
              '## sewing.svg', '', 'Pattern pieces generated with FreeSewing 4.10.2 (Teagan).', '',
              (licences/'FreeSewing-LICENSE.txt').read_text(encoding='utf-8').strip(), '']
    (OUT/'LICENSES.txt').write_text('\n'.join(notice), encoding='utf-8', newline='\n')
    for e in examples:
        print(e['id'], sum(e['quantities'].values()) if e['quantities'] else 'default', 'parts')


if __name__ == '__main__':
    main()
