"""Build shelves from source outlines, including pairs of complementary orthogonal parts."""
import argparse
from collections import defaultdict
from functools import partial
import json
from math import pi
from pathlib import Path
import subprocess
import sys
import time
from zipfile import ZipFile

import numpy as np
from construct import RESULTS, construct
sys.path.insert(0,str(RESULTS/"h5-bracket-axis-compaction-20261120"))
