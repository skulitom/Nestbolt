def translate(r,dx,dy):
    l,u,b,t,k,a,x,y,m = r
    return l+dx,u+dx,b+dy,t+dy,k,a,x+dx,y+dy,m


def catalogue(job, layout, width, height, gap, padding, maximum_size=2):
    ids = [p["id"] for p in job["parts"]]
    quantities = tuple(p["quantity"] for p in job["parts"])
    shapes = []
    tiles = defaultdict(list)
    def offer(members):
        x0 = min(r[0] for r in members)
        y0 = min(r[2] for r in members)
        w = max(r[1] for r in members)-x0
        h = max(r[3] for r in members)-y0
        key = tuple(sum(r[4]==k for r in members) for k in ids)
        if any(a>wanted for a,wanted in zip(key,quantities)) or w>width or h>height:
            return
        old = tiles[key]
        if any(a<=w+1e-8 and b<=h+1e-8 for a,b,_ in old):
            return
        tiles[key] = [t for t in old if not (w<=t[0]+1e-8 and h<=t[1]+1e-8)]
        tiles[key].append((w,h,[translate(r,-x0,-y0) for r in members]))
    for p in job["parts"]:
        # Filled outers are a conservative representation. Holes stay in the
        # public library and retain their original complete cutting contours.
        rects = [r for poly in p["geometry"] for r in rectangles(dict(outer=poly["outer"],holes=[]))]
        for d in p["rotations"]["degrees"]:
            theta = d*pi/180
            trans = dict(translation=[0,0],rotation_radians=theta,mirrored=False)
            rs = np.array([oriented(r,trans,"down") for r in rects])
            lo,hi,b,t = rs[:,0].min(),rs[:,1].max(),rs[:,2].min(),rs[:,3].max()
            shape = (0,hi-lo,0,t-b,p["id"],theta,-lo,-b,False)
            rs -= [lo,lo,b,b]
            shapes.append((rs,shape))
            offer([shape])
    oriented_boxes = {(r[4],r[5]):(boxes,r) for boxes,r in shapes}
    def contacts(a,members,b,pb):
        extent_x = max(p[1] for p in members)
        extent_y = max(p[3] for p in members)
        # Forbidden translations are the open rectangles generated by the
        # Minkowski differences of each rectangle pair, plus the kerf.
        obstacle = (a[:,None,:]-b[None,:,[1,0,3,2]]).reshape(-1,4)+[-gap,gap,-gap,gap]
        xs = np.unique(np.r_[obstacle[:,:2].ravel(),0,extent_x-pb[1]])
        ys = np.unique(np.r_[obstacle[:,2:].ravel(),0,extent_y-pb[3]])
        for x in xs:
            active = obstacle[(x>obstacle[:,0]+1e-9)&(x<obstacle[:,1]-1e-9)]
            blocked = np.any((ys[:,None]>active[:,2]+1e-9)&(ys[:,None]<active[:,3]-1e-9),axis=1)
            for y in ys[~blocked]:
                offer(members+[translate(pb,x,y)])
    for ai,(a,pa) in enumerate(shapes):
        for b,pb in shapes[ai:]:
            contacts(a,[pa],b,pb)
    for count in range(2,maximum_size):
        parents = [m for key,items in tiles.items() if sum(key)==count for _,_,m in items]
        for members in parents:
            boxes = []
            for r in members:
                local,origin = oriented_boxes[r[4],r[5]]
                dx,dy = r[6]-origin[6],r[7]-origin[7]
                boxes.append(local+[dx,dx,dy,dy])
            a = np.vstack(boxes)
            for b,pb in shapes:
                contacts(a,members,b,pb)
    # At each candidate shelf height, enumerate full-width rows of any
    # combination of the eligible pieces/paired tiles, keeping the narrowest
    # row for each exact inventory.
    options = [(key,w,h,m) for key,items in tiles.items() for w,h,m in items]
    found = {}
    for limit in sorted(set(round(h,7) for _,_,h,_ in options)):
        eligible = {}
        for key,w,h,m in options:
            if h<=limit+1e-7 and (key not in eligible or w<eligible[key][0]):
                eligible[key] = (w,m)
        costs = {(0,)*len(ids):(0,[])}
        by_count = defaultdict(set)
        by_count[0].add((0,)*len(ids))
        for size in range(sum(quantities)+1):
            for key in sorted(by_count[size]):
                prev,row = costs[key]
                for extra,(w,members) in eligible.items():
                    w_new = prev+(gap if row else 0)+w
                    if w_new>width:
                        continue
                    counts = tuple(a+b for a,b in zip(key,extra))
                    if any(n>q for n,q in zip(counts,quantities)):
                        continue
                    if counts not in costs or w_new<costs[counts][0]-1e-8:
                        costs[counts] = w_new,row+[(prev+(gap if row else 0),members)]
                        by_count[sum(counts)].add(counts)
        for counts,(w,row) in costs.items():
            if row and counts not in found:
                placed = [translate(r,x,0) for x,members in row for r in members]
                actual_height = max(r[3] for r in placed)
                found[counts] = (actual_height,1,placed)
    return quantities,found


def run(binary,folder,inputs,maximum_size):
    records = []
    for path in inputs:
        dest = folder/path.stem
        dest.mkdir(parents=True,exist_ok=True)
        with ZipFile(path) as archive:
            job,layout = [json.loads(archive.read(n)) for n in ("nested/job.json","nested/layout.json")]
            for n in ("library.json","request.json"):
                (dest/n).write_bytes(archive.read(n))
        start = time.monotonic()
        trial,record = construct(job,layout,partial(catalogue,maximum_size=maximum_size))
        record.update(source=str(path),seconds=time.monotonic()-start,maximum_size=maximum_size)
        if trial:
            out = dest/"layout.json"
            out.write_text(json.dumps(trial),encoding="utf-8",newline="\n")
            proc = subprocess.run([binary,"validate","--library",dest/"library.json","--request",dest/"request.json",
                                   "--layout",out],capture_output=True)
            (dest/"validation.json").write_bytes(proc.stdout)
            check = json.loads(proc.stdout)
            record["valid"] = proc.returncode==0 and check["valid"]
            if record["valid"]:
                record["material"] = check["metrics"]["normalized_material"]
                record["saved_fraction"] = sum(s["saved_length_mm"] for s in check["common_line"])/sum(
                    s["cut_length_without_common_mm"] for s in check["common_line"])
        records.append(record)
        print(path.stem,record.get("valid"),record.get("material"),record.get("saved_fraction"),record["seconds"],flush=True)
    (folder/"results.json").write_text(json.dumps(records,indent=2)+"\n",encoding="utf-8",newline="\n")


if __name__=="__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary",type=Path)
    parser.add_argument("out",type=Path)
    parser.add_argument("inputs",nargs="+",type=Path)
    parser.add_argument("--size",type=int,default=2)
    args = parser.parse_args()
    run(args.binary.resolve(),args.out.resolve(),args.inputs,args.size)
